/**
 * Build the checked-in, publishable scenario package.
 *
 * Output: packages/scenario-source-brief/ — a complete DSH plugin package with
 * package.json (dsh.bundle), cordis.patch.yml, dist/index.js, assets, SKILL.md,
 * examples, README and LICENSE.
 *
 * Trials run on the offline mock engine, so the build stays at verification
 * state "packaged" and every run record is marked engineKind "mock".
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createAuthorTools } from "@workflow-forge/author";
import { createMockEngine, defaultResponder, fakeExec } from "@workflow-forge/runtime";
import type { JsonValue } from "@workflow-forge/spec";

const root = process.cwd();
const exampleDir = join(root, "examples", "source-brief");
const targetDir = join(root, "packages", "scenario-source-brief");
const dataDir = join(root, ".forge", "release");

const PACKAGE_NAME = "dsh-scenario-source-brief";
const TRIAL_FIXTURES = ["01-normal.json", "02-conflicting.json", "05-second-topic.json"];

const spec = JSON.parse(readFileSync(join(exampleDir, "spec.json"), "utf8")) as JsonValue;
const skillBody = readFileSync(join(exampleDir, "SKILL.md"), "utf8");
const examples = readdirSync(join(exampleDir, "fixtures"))
  .filter((name) => /^\d\d-.*\.json$/.test(name))
  .sort()
  .map((name) => ({ path: `examples/fixtures/${name}`, content: readFileSync(join(exampleDir, "fixtures", name), "utf8") }));

function responder(context: Parameters<typeof defaultResponder>[0]): JsonValue | null {
  const args = context.args as Record<string, JsonValue>;
  const topic = typeof args["topic"] === "string" ? (args["topic"] as string) : "";
  if (topic.includes("客服知识库迁移") && context.label === "m3") return null;
  return defaultResponder(context);
}

const mock = createMockEngine({ responder });
const author = createAuthorTools({
  dataDir,
  outputDir: targetDir,
  engine: mock.engine,
  engineKind: "mock",
  hostVersion: "offline-mock",
  profile: {
    packageName: PACKAGE_NAME,
    skillBody,
    examples,
    targetDir,
    dshVersion: "0.2.1-rc.3",
  },
});

async function call(name: string, args: Record<string, JsonValue>): Promise<Record<string, JsonValue>> {
  const tool = author.tools.find((entry) => entry.name === name);
  if (!tool) throw new Error(`unknown tool ${name}`);
  return (await tool.execute(args, fakeExec())) as Record<string, JsonValue>;
}

// Start from clean state: the package and its trial set must be reproducible.
rmSync(targetDir, { recursive: true, force: true });
mkdirSync(targetDir, { recursive: true });
rmSync(dataDir, { recursive: true, force: true });
mkdirSync(dataDir, { recursive: true });

const validated = await call("forge_validate", { spec });
if (validated["ok"] !== true) {
  console.error(JSON.stringify(validated, null, 2));
  process.exit(1);
}
const draftRef = String(validated["draftRef"]);
console.log(`draftRef: ${draftRef}`);
console.log(`staticReport: ${JSON.stringify(validated["staticReport"])}`);

for (const fixture of TRIAL_FIXTURES) {
  const input = JSON.parse(readFileSync(join(exampleDir, "fixtures", fixture), "utf8")) as JsonValue;
  const trial = await call("forge_trial", { draftRef, input });
  console.log(`trial ${fixture}: ${String(trial["state"])} (${String(trial["inputHash"])})`);
  if (trial["state"] !== "COMPLETED") {
    console.error("a packaging trial must be COMPLETED");
    process.exit(1);
  }
}

const packaged = await call("forge_package", { draftRef });
if (packaged["ok"] !== true) {
  console.error(JSON.stringify(packaged, null, 2));
  process.exit(1);
}

const buildHash = String(packaged["buildHash"]);
const files = packaged["files"] as unknown as string[];
writeFileSync(
  join(targetDir, "BUILD-SUMMARY.md"),
  [
    "# Build summary",
    "",
    `- package: \`${PACKAGE_NAME}@0.1.0\``,
    `- buildHash: \`${buildHash}\``,
    `- draftHash: \`${draftRef}\``,
    `- verification: \`${JSON.stringify(packaged["verification"])}\``,
    `- trials: ${TRIAL_FIXTURES.join(", ")}`,
    "",
    "Generated by `pnpm build:scenario`. Do not edit by hand.",
    "",
  ].join("\n"),
  "utf8",
);

console.log(`buildHash: ${buildHash}`);
console.log(`packageDir: ${targetDir}`);
console.log(`files: ${files.length}`);
console.log(`verification: ${JSON.stringify(packaged["verification"])}`);
await author.shutdown();
