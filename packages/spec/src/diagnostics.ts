export type DiagnosticCode = (typeof DIAGNOSTIC_CODES)[keyof typeof DIAGNOSTIC_CODES];

export function diagnostic(input: {
  code: DiagnosticCode | string;
  message: string;
  fieldPath?: string;
  nodeId?: string;
  fix?: string;
  severity?: DiagnosticSeverity;
}): Diagnostic {
  const out: Diagnostic = {
    code: input.code,
    severity: input.severity ?? "error",
    fieldPath: input.fieldPath ?? "",
    message: input.message,
  };
  if (input.nodeId !== undefined) out.nodeId = input.nodeId;
  if (input.fix !== undefined) out.fix = input.fix;
  return out;
}

export function hasErrors(diagnostics: readonly Diagnostic[]): boolean {
  return diagnostics.some((d) => d.severity === "error");
}

export class ForgeDiagnosticsError extends Error {
  readonly diagnostics: Diagnostic[];
  constructor(message: string, diagnostics: Diagnostic[]) {
    super(message);
    this.name = "ForgeDiagnosticsError";
    this.diagnostics = diagnostics;
  }
}

export function formatDiagnostic(d: Diagnostic): string {
  const where = [d.nodeId ? `node ${d.nodeId}` : "", d.fieldPath].filter(Boolean).join(" ");
  return `${d.code}${where ? ` @ ${where}` : ""}: ${d.message}${d.fix ? ` (fix: ${d.fix})` : ""}`;
}
